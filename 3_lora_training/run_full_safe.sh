#!/bin/bash
# ==============================================================================
# Qwen3-4B 软标签蒸馏 - WSL 安全执行脚本 (训练 + 评估)
# ==============================================================================

set -e

# ==============================================================================
# 配置区
# ==============================================================================

WSL_PROJECT="/mnt/d/0321/sentiment-distillation-pipeline"
MODEL="unsloth/Qwen3-4B-unsloth-bnb-4bit"
DATA_FULL="${WSL_PROJECT}/data/conversations/train_conversations.json"
TEST_DATA="${WSL_PROJECT}/data/conversations/test_conversations.json"
OUTPUT_DIR="${WSL_PROJECT}/3_lora_training/models/qwen3-4b-soft-full"

# ==============================================================================
# Step 1: 全量训练
# ==============================================================================

echo ""
echo "=============================================================="
echo "Step 1: 全量软标签训练 (7172条, 3epochs)"
echo "=============================================================="
echo "预估时间: ~4小时"
echo "=============================================================="

cd "${WSL_PROJECT}/3_lora_training"

python3 train_soft_label.py \
    --model "${MODEL}" \
    --data "${DATA_FULL}" \
    --output "${OUTPUT_DIR}" \
    --epochs 3 \
    --batch 1 \
    --grad-acc 16 \
    --lr 2e-5 \
    --temperature 2.0 \
    --alpha 0.5

echo "训练完成 ✓"

# ==============================================================================
# Step 2: 安全评估 (逐条推理)
# ==============================================================================

echo ""
echo "=============================================================="
echo "Step 2: 内存安全评估 (逐条推理)"
echo "=============================================================="
echo "预估时间: ~20分钟"
echo "=============================================================="

cd "${WSL_PROJECT}/4_evaluation"

python3 eval_safe.py \
    --model "${OUTPUT_DIR}" \
    --base-model "${MODEL}" \
    --data "${TEST_DATA}" \
    --samples 897 \
    --max-tokens 256 \
    --output "${WSL_PROJECT}/6_experiments_results/soft_full_eval.json"

echo "评估完成 ✓"

# ==============================================================================
# Step 3: 结果分析
# ==============================================================================

echo ""
echo "=============================================================="
echo "Step 3: 结果分析"
echo "=============================================================="

EVAL_FILE="${WSL_PROJECT}/6_experiments_results/soft_full_eval.json"

if [ -f "${EVAL_FILE}" ]; then
    echo ""
    echo "软标签蒸馏结果:"
    python3 -c "
import json
with open('${EVAL_FILE}') as f:
    r = json.load(f)
print(f'  准确率: {r[\"accuracy\"]:.2f}%')
print(f'  总样本: {r[\"total\"]}')
print(f'  正确: {r[\"correct\"]}')
print(f'  解析错误: {r[\"parse_errors\"]}')
"
    echo ""
    echo "对比硬标签基线:"
    echo "  硬标签准确率: 79.69%"
    echo "  硬标签中性召回: 72.1%"
fi

echo ""
echo "=============================================================="
echo "完整流程执行完毕"
echo "=============================================================="